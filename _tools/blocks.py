# -*- coding: utf-8 -*-
"""블록 번호와 차시의 대응 — 이 표가 단 하나의 근거다.

과정안 파일 이름(BXX_1~2차시_활동지도안.hwpx)과 진행 시트에서 그대로 옮겼다.
허브·각 쪽의 표시는 모두 여기를 본다. 표시는 `B17`이 아니라 `5~6`이다.
"""

LESSON = {
    'B01': (5, '1~2'),   'B02': (5, '3~4'),   'B03': (5, '5~6'),   'B04': (5, '7~8'),
    'B05': (5, '9~10'),  'B06': (5, '11~12'), 'B07': (5, '13~14'), 'B08': (5, '15~16'),
    'B09': (5, '17~18'), 'B10': (5, '19~20'), 'B11': (5, '21~24'), 'B12': (5, '25~28'),
    'B13': (5, '29~30'), 'B14': (5, '31~32'),
    'B15': (6, '1~2'),   'B16': (6, '3~4'),   'B17': (6, '5~6'),   'B18': (6, '7~8'),
    'B19': (6, '9~10'),  'B20': (6, '11~12'), 'B21': (6, '13~14'), 'B22': (6, '15~16'),
    'B23': (6, '17~18'), 'B24': (6, '19~20'), 'B25': (6, '21~24'), 'B26': (6, '25~26'),
    'B27': (6, '27~30'), 'B28': (6, '31~32'),
}


def grade(bid: str) -> int:
    return LESSON[bid][0]


def label(bid: str) -> str:
    """쪽 위와 허브 카드에 찍는 말. 예: '17~18'"""
    return LESSON[bid][1]


def full(bid: str) -> str:
    """헷갈릴 자리에서 쓰는 긴 말. 예: '6학년 17~18차시'"""
    g, n = LESSON[bid]
    return '%d학년 %s차시' % (g, n)
